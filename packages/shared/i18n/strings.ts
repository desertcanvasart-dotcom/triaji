// ─── Type-safe accessor ─────────────────────────────────────────────────────

type StringNode = { ar: string; en: string };

/**
 * Resolve a nested key path to a localized string.
 * @example t('chat.send', 'en') → 'Send'
 * @example t('common.appName', 'ar') → 'ترياچي'
 */
export function t(key: string, lang: Lang): string {
  const parts = key.split('.');
  let current: unknown = UI_STRINGS;

  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = (current as Record<string, unknown>)[part];
    } else {
      console.warn(`[i18n] Missing key: ${key}`);
      return key;
    }
  }

  if (current && typeof current === 'object' && 'ar' in current && 'en' in current) {
    return (current as StringNode)[lang];
  }

  console.warn(`[i18n] Invalid key: ${key}`);
  return key;
}

